// Obspec build: bundles the bridge, the plugin sandbox and the plugin UI.
// The UI is emitted as a single self-contained HTML file (Figma requires that).
import * as esbuild from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const watch = process.argv.includes('--watch');
const r = (p) => path.join(root, p);

await mkdir(r('dist'), { recursive: true });
await mkdir(r('bridge/dist'), { recursive: true });

/** @type {import('esbuild').BuildOptions} */
const bridge = {
  entryPoints: [r('bridge/src/server.ts'), r('bridge/src/cli.ts')],
  outdir: r('bridge/dist'),
  bundle: true, platform: 'node', format: 'esm', target: 'node18', sourcemap: 'inline', logLevel: 'info',
  banner: { js: '// Obspec Bridge — generated by scripts/build.mjs' },
};

/** @type {import('esbuild').BuildOptions} */
const sandbox = {
  entryPoints: [r('src/plugin/code.ts')],
  outfile: r('dist/code.js'),
  bundle: true, platform: 'browser', format: 'iife', target: 'es2017', logLevel: 'info',
};

const inlineHtml = {
  name: 'inline-html',
  setup(build) {
    build.onEnd(async (result) => {
      if (result.errors.length) return;
      const js = result.outputFiles.find((f) => f.path.endsWith('.js'))?.text ?? '';
      const css = result.outputFiles.find((f) => f.path.endsWith('.css'))?.text ?? '';
      const tpl = await readFile(r('src/ui/index.html'), 'utf8');
      const html = tpl.replace('/*__CSS__*/', () => css).replace('/*__JS__*/', () => js.replace(/<\/script>/g, '<\\/script>'));
      await writeFile(r('dist/ui.html'), html);
      console.log(`  dist/ui.html  ${(html.length / 1024).toFixed(1)}kb`);
    });
  },
};

/** @type {import('esbuild').BuildOptions} */
const ui = {
  entryPoints: [r('src/ui/ui.ts')],
  outdir: r('dist/.ui'), write: false,
  bundle: true, platform: 'browser', format: 'iife', target: 'es2019', logLevel: 'info',
  loader: { '.svg': 'text' },
  plugins: [inlineHtml],
};

/** Preview harness (mock Figma sandbox + scenario runner) — not shipped with the plugin. */
const harness = {
  entryPoints: [r('preview/harness.ts')],
  outfile: r('preview/dist/harness.js'),
  bundle: true, platform: 'browser', format: 'iife', target: 'es2020', logLevel: 'info', sourcemap: 'inline',
};

if (watch) {
  const ctxs = await Promise.all([bridge, sandbox, ui, harness].map((o) => esbuild.context(o)));
  await Promise.all(ctxs.map((c) => c.watch()));
  console.log('watching…');
} else {
  await Promise.all([bridge, sandbox, ui, harness].map((o) => esbuild.build(o)));
}
